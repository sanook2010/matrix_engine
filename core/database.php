    try {
        $pdo = new PDO("mysql:host={$GLOBALS["host"]};dbname={$GLOBALS["db"]};charset=utf8mb4", $GLOBALS["user"], $GLOBALS["pass"], [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
        ]);
        return $pdo;
    } catch (PDOException $e) {
        die('❌ DB Connect Error: ' . $e->getMessage());
    }
}

function db_find($col, $table, $whereCol, $whereVal) {
    $pdo = db_connect();
    $stmt = $pdo->prepare("SELECT `$col` FROM `$table` WHERE `$whereCol` = ? LIMIT 1");
    $stmt->execute([$whereVal]);
    return $stmt->fetchColumn();
}

function db_select($cols, $table, $whereCol = null, $whereVal = null) {
    $pdo = db_connect();
    $sql = "SELECT $cols FROM `$table`";
    $param = [];
    if ($whereCol !== null) {
        $sql .= " WHERE `$whereCol` = ?";
        $param = [$whereVal];
    }
    $stmt = $pdo->prepare($sql);
    $stmt->execute($param);
    return $stmt->fetchAll();
}

function db_insert($table, $data) {
    $pdo = db_connect();
    $keys = array_keys($data);
    $placeholders = array_fill(0, count($keys), '?');
    $stmt = $pdo->prepare("INSERT INTO `$table` (`" . implode('`,`', $keys) . "`) VALUES (" . implode(',', $placeholders) . ")");
    $stmt->execute(array_values($data));
    return $pdo->lastInsertId();
}

function db_update($table, $data, $whereCol, $whereVal) {
    $pdo = db_connect();
    $set = [];
    foreach (array_keys($data) as $k) $set[] = "`$k` = ?";
    $stmt = $pdo->prepare("UPDATE `$table` SET " . implode(',', $set) . " WHERE `$whereCol` = ?");
    $vals = array_values($data);
    $vals[] = $whereVal;
    return $stmt->execute($vals);
}

function db_delete($table, $whereCol, $whereVal) {
    $pdo = db_connect();
    $stmt = $pdo->prepare("DELETE FROM `$table` WHERE `$whereCol` = ?");
    return $stmt->execute([$whereVal]);
}

