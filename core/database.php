// 🕵️ พร็อกซี่ในตัว — ดึง+แคช ไม่เปิดเผยต้นทาง
// ==============================================================
function proxy_fetch($url, $ttl = 3600) {
    $cacheDir = WEBROOT . '/.proxy_cache/';
    is_dir($cacheDir) || mkdir($cacheDir, 0700, true);
    $cacheFile = $cacheDir . md5($url) . '.cache';

    if (file_exists($cacheFile)) {
        $c = @unserialize(file_get_contents($cacheFile));
        if (is_array($c) && isset($c['time'], $c['body']) && (time() - $c['time'] < $ttl)) {
            return $c['body'];
        }
        @unlink($cacheFile);
    }

    $ch = curl_init($url);
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_FOLLOWLOCATION => true,
        CURLOPT_SSL_VERIFYPEER => false,
        CURLOPT_TIMEOUT        => 15,
        CURLOPT_USERAGENT      => 'Mozilla/5.0',
    ]);
    $body = curl_exec($ch);
    curl_close($ch);

    if ($body) {
        file_put_contents($cacheFile, serialize(['time' => time(), 'body' => $body]));
    }
    return $body;
}

