// 📁 ระบบไฟล์ — MD5 + Base64 ไม่ต้องฐานข้อมูล
// ==============================================================
function base64_url_encode($input) {
    return strtr(base64_encode($input), '+/=', '._-');
}
function base64_url_decode($input) {
    return base64_decode(strtr($input, '._-', '+/='));
}
function fwrite_stream($file, $content, $mode = 'a+') {
    $fp = fopen($file, $mode);
    if ($fp === false) return 0;
    $written = fwrite($fp, $content);
    fclose($fp);
    return $written !== false ? $written : 0;
}
function file_check($store, $fileKey) {
    if ($store == null) return null;
    $md5 = md5($fileKey);
    foreach (file($store, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        if (strncmp($line, $md5, 32) === 0) {
            return base64_url_decode(substr($line, 32));
        }
    }
    return null;
}
function file_add($store, $fileKey, $data) {
    $md5 = md5($fileKey);
    $line = $md5 . base64_url_encode($data) . "\n";
    return fwrite_stream($store, $line);
}
function file_update($store, $fileKey, $newData) {
    if (!file_exists($store)) return false;
    $md5 = md5($fileKey);
    $lines = file($store, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    $fp = fopen($store, 'w');
    if ($fp === false) return false;
    $found = false;
    foreach ($lines as $line) {
        if (strncmp($line, $md5, 32) === 0) {
            fwrite($fp, $md5 . base64_url_encode($newData) . "\n");
            $found = true;
        } else {
            fwrite($fp, $line . "\n");
        }
    }
    if (!$found) fwrite($fp, $md5 . base64_url_encode($newData) . "\n");
    fclose($fp);
    return true;
}

